/**
 * 문의 표에서 사람이 사라지지 않는지 본다.
 *
 * 학부모지원센터 보도자료를 넣었더니 세 사람 중 한 사람만 남고 첫 줄과 끝 줄이
 * 통째로 비어 나왔다. 원인은 두 가지였다.
 *   ① ‘선임’·‘주임’ 이 직위 목록에 없어 그 줄이 그냥 지나갔고, 뒤따르는 이름과
 *      전화번호는 이미 찬 칸에 막혀 함께 사라졌다.
 *   ② 첫 칸(과장 자리)을 관리직 전용으로 두어, 관리직이 없는 부서는 첫 줄이 비었다.
 */
import { parseContacts } from './lib.mjs';

let bad = 0;
const check = (name, got, want) => {
  const ok = String(got) === String(want);
  if (!ok) bad++;
  console.log(`  ${ok ? '✓' : '✗'} ${name} — ${got}${ok ? '' : ` (기대 ${want})`}`);
};
const show = (c) => c.사람.map((p) => `${p.label}/${p.name}/${p.tel}`).join(' · ');

console.log('목록에 없는 직위여도 사람을 버리지 않는다');
const 학부모 = parseContacts([
  '담당 부서', '(문   의)', '학부모지원센터',
  '학부모지원팀장', '김학엽', '063-223-1396',
  '학부모지원팀 선임', '김영랑', '063-223-1396',
  '학부모지원팀 주임', '김병도', '063-223-1396',
]);
check('부서', 학부모.부서, '학부모지원센터');
check('세 사람 다 남는다', 학부모.사람.length, 3);
check('직위 글자는 그대로', show(학부모),
  '학부모지원팀장/김학엽/063-223-1396 · 학부모지원팀 선임/김영랑/063-223-1396 · 학부모지원팀 주임/김병도/063-223-1396');

console.log('\n아는 직위는 전과 같이 읽는다');
const 미래 = parseContacts([
  '담당 부서', '(문   의)', '미래교육과',
  '과장', '장기영', '063-239-3202',
  '전산행정담당', '조준연', '063-239-3226',
  '주무관', '류무출', '063-239-3230',
]);
check('부서', 미래.부서, '미래교육과');
check('세 사람', show(미래),
  '과장/장기영/063-239-3202 · 전산행정담당/조준연/063-239-3226 · 주무관/류무출/063-239-3230');

console.log('\n글자 사이를 띄운 서식도 읽는다');
const 김제 = parseContacts([
  '담당 부서', '(문   의)', '교육지원과',
  '행정지원과장', '김영주', '063-540-2560',
  '중 등 담 당', '채수복', '063-540-2573',
  '담  당  자', '고은아', '063-540-2571',
]);
check('세 사람', 김제.사람.length, 3);
check('직위 글자는 그대로', 김제.사람.map((p) => p.label).join(','), '행정지원과장,중 등 담 당,담  당  자');

console.log('\n표가 없으면 빈손');
check('사람 없음', parseContacts(['제목만 있는 글']).사람.length, 0);

console.log(bad ? '\n✗ 어긋난 곳이 있습니다' : '\n✓ 문의 표에서 사람이 안 사라집니다');
process.exit(bad ? 1 : 0);
