/* 2. 무엇은 절대 바뀌면 안 되는가                                       */
/* ------------------------------------------------------------------ */

/** 숫자·날짜·비율 — 하나라도 달라지면 사실이 바뀐 것이다 */
const NUMBERS = /\d[\d,.]*/g;
/** 한글(로마자) 병기 — 이미 규범에 맞는 형태다 */
const BYUNGGI = /[가-힣]+\([A-Za-z][A-Za-z0-9&.\-+]*\)/g;
/** 자리표시가 섞인 답 — 그대로 넣을 수 없다 */
const PLACEHOLDER = /[~]|\((으|이|가|을|를|과|와|는|은|아|야)\)/;

const bag = (s: string, re: RegExp) => (s.match(re) ?? []).slice().sort().join('|');

export type Violation =
  | '지표 이름이 목록에 없음'
  | '원문에 없는 조각을 지어냄'
  | '숫자가 바뀜'
  | '병기를 떼어 냄'
  | '자리표시가 섞임'
  | '고친 말이 비었음';

/**
 * 고쳐 넣겠다는 말이 규약을 지키는지 본다.
 *
 * 부탁이 아니라 확인이다. 어긴 것은 화면에 올리지 않는다.
 */
export function checkReplacement(from: string, to: string): Violation | null {
  const t = (to ?? '').trim();
  if (!t) return '고친 말이 비었음';
  if (PLACEHOLDER.test(t)) return '자리표시가 섞임';
  // 숫자는 늘리는 것도 줄이는 것도 안 된다. 있던 그대로여야 한다.
  if (bag(from, NUMBERS) !== bag(t, NUMBERS)) return '숫자가 바뀜';
  // ‘높이기(UP)’ → ‘높이기’ 처럼 병기를 떼어 내는 것을 막는다. 다는 것은 괜찮다.
  const before = (from.match(BYUNGGI) ?? []).length;
  const after = (t.match(BYUNGGI) ?? []).length;
  if (after < before) return '병기를 떼어 냄';
  return null;
}
