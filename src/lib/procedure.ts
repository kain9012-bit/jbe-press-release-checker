/** AI 가 낼 수 있는 지표 이름 (이 밖의 것은 버린다) */
export const STEP_IDS = new Set(STEPS.map((s) => s.id));
export const AXIS_OF: Record<string, Step['axis']> = Object.fromEntries(
  STEPS.map((s) => [s.id, s.axis]),
) as Record<string, Step['axis']>;

/** 절차를 지시문에 넣을 글로 만든다 */
export function procedureText(): string {
  return STEPS.map((s, i) => {
    const skip = s.skip ? `\n   보지 않는 것: ${s.skip}` : '';
    return `${i + 1}. [${s.id}] (${s.axis})\n   보는 것: ${s.look}${skip}`;
  }).join('\n');
}

