/**
 * 이 요건을 무엇이 답하는가.
 *   고침 — AI 가 어긋난 자리를 찾아 고쳐 온다. 걸린 것은 수정본에 반영돼 있다.
 *   판정 — AI 가 고치지는 않고 어긋나 보이는 곳만 짚는다(글 짜임에 관한 것이라
 *          기계가 손대면 사실이 바뀐다). 최종 판단은 작성자다.
 *   계산 — 판단이 아니라 셈이다. 코드가 재서 사실을 적는다.
 */
