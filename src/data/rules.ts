/** 두음 법칙: 앞 글자 받침이 없거나 ‘ㄴ’이면 ‘율/열’, 그 밖에는 ‘률/렬’ */
export function checkDueum(text: string) {
  const hits: { index: number; wrong: string; right: string; why: string }[] = [];
  const re = /([가-힣])(률|율)/g;
  let m: RegExpExecArray | null;
  while ((m = re.exec(text))) {
    const prev = m[1];
    const cur = m[2];
    const code = prev.charCodeAt(0) - 0xac00;
    if (code < 0 || code > 11171) continue;
    const jong = code % 28; // 0 = 받침 없음, 4 = ㄴ
    const needSoft = jong === 0 || jong === 4;
    const soft = cur === '율';
    if (needSoft === soft) continue;
    const right = cur === '률' ? '율' : '률';
    hits.push({
      index: m.index + 1,
      wrong: cur,
      right,
      why: needSoft
        ? `앞 글자에 받침이 없거나 받침이 ‘ㄴ’이면 ‘${right}’로 적는다.`
        : `앞 글자에 ‘ㄴ’ 외의 받침이 있으면 ‘${right}’로 적는다.`,
    });
  }
  return hits;
}

