const esc = (s: string) => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');

function fromPairs(
  prefix: string,
  axis: Axis,
  sub: string,
  src: string,
  pairs: [string, string][] | [string, string, string][],
  defWhy: string,
  manual = false,
): PatternRule[] {
  const out: PatternRule[] = [];
  pairs.forEach((p, i) => {
    const [w, r, why] = p as [string, string, string?];
    if (!r || w === r) return;
    out.push(
      R(`${prefix}${i}`, axis, sub, new RegExp(esc(w), 'g'), r, why || defWhy, src, manual),
    );
  });
  return out;
}

